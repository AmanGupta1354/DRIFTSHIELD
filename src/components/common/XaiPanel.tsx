import { motion } from 'framer-motion';
import { Cpu } from 'lucide-react';
import { useMemo, type ReactNode } from 'react';
import { useOpen } from '../../hooks/useOpen';
import { isBlocking } from '../../lib/riskScoring';
import { TONE, cn, actionTone, scoreTone } from '../../lib/utils';
import { explainEvent, type ExplainOptions } from '../../lib/xai';
import type { Alert, SecEvent, Signal } from '../../types';
import { ActionBadge, Badge, SeverityBadge } from '../ui/Badges';
import { Tip } from '../ui/Controls';

const H = ({ children, hint }: { children: ReactNode; hint?: ReactNode }) => (
  <div className="mb-1.5 mt-4 flex items-center justify-between gap-2 first:mt-0">
    <h4 className="font-mono text-[10.5px] font-semibold uppercase tracking-[0.16em] text-muted">{children}</h4>
    {hint}
  </div>
);

const LEVEL_TONE = { High: 'danger', Medium: 'warn', Low: 'neon' } as const;

/**
 * "DriftShield XAI — Decision Explanation". Everything shown is generated from the structured detector
 * evidence of the selected event by deterministic templates (see lib/xai.ts).
 */
export function XaiPanel({ event, alert, signals, related, live, pending, className }: {
  event: SecEvent; alert?: Alert; signals?: Signal[]; related?: string[]; live?: boolean; pending?: boolean; className?: string;
}) {
  const { openEvent } = useOpen();
  const opts: ExplainOptions = { alert, signals, related: related ?? alert?.eventIds };
  const x = useMemo(() => explainEvent(event, opts), [event, alert, signals, related]); // eslint-disable-line react-hooks/exhaustive-deps
  const blocked = isBlocking(x.decision);
  const whyTitle = blocked ? 'Why was the operation blocked?' : x.decision === 'step_up' ? 'Why was it held?' : x.decision === 'watch' ? 'Why is it being watched?' : 'Why was it allowed?';

  return (
    <section className={cn('rounded-xl border border-line/10 bg-bg/40', className)} aria-label="Decision explanation">
      <header className="flex items-center justify-between gap-2 border-b border-line/[0.07] px-4 py-2.5">
        <div className="flex items-center gap-2"><Cpu size={14} className="text-neon" aria-hidden /><h3 className="text-[13px] font-semibold">DriftShield XAI — Decision Explanation</h3></div>
        <Tip text="Explanations are generated by deterministic rules from the detector evidence. No LLM or external service is used."><Badge tone="muted">rule-based</Badge></Tip>
      </header>

      <motion.div key={event.event_id + (live ? x.score : '')} initial={{ opacity: 0.4 }} animate={{ opacity: 1 }} className="p-4">
        <H>What happened?</H>
        <p className="text-[13px] leading-relaxed">{x.what}</p>

        <H hint={<span className="font-mono text-[10px] text-muted">{x.flagged.length} signal{x.flagged.length === 1 ? '' : 's'}</span>}>Why was it flagged?</H>
        {x.flagged.length === 0 ? <p className="text-xs text-muted">{pending ? 'Detectors are still evaluating…' : 'No detector triggered for this event.'}</p> : (
          <ul className="space-y-1.5">
            {x.flagged.map((f) => (
              <li key={f.title + f.detail} className="rounded-lg border border-line/[0.08] bg-bg/50 px-3 py-2">
                <div className="flex flex-wrap items-center gap-1.5 text-[12.5px] font-medium">{f.title}{f.hard && <Badge tone="danger">hard</Badge>}{f.policyId && <Badge tone="muted">{f.policyId}</Badge>}</div>
                <p className="mt-0.5 text-[11.5px] leading-snug text-muted">{f.detail}</p>
              </li>
            ))}
          </ul>
        )}

        {x.breakdown.length > 0 && (
          <>
            <H hint={<Tip text="Evidence strength = family weight × strongest signal in the family. Illustrative, not a calibrated probability."><span className="cursor-help font-mono text-[10px] text-muted underline decoration-dotted">how to read</span></Tip>}>Risk breakdown</H>
            <ul className="space-y-2">
              {x.breakdown.map((b, i) => (
                <li key={b.label} className="grid grid-cols-[minmax(0,9.5rem)_1fr_auto] items-center gap-3 text-xs">
                  <span className="truncate">{b.label}</span>
                  <span className="h-2 overflow-hidden rounded-full bg-fg/10">
                    <motion.span className={cn('block h-full rounded-full', TONE[LEVEL_TONE[b.level]].dot)} initial={{ width: 0 }} animate={{ width: `${Math.max(4, b.contribution * 100)}%` }} transition={{ delay: i * 0.06, duration: 0.5 }} />
                  </span>
                  <Badge tone={LEVEL_TONE[b.level]} className="w-16 justify-center">{b.level}</Badge>
                </li>
              ))}
            </ul>
            <p className="mt-1.5 text-[10.5px] text-muted">Score {x.score}/100 combines these with a bounded noisy-OR (strongest signal per family).</p>
          </>
        )}

        {pending ? (
          <p className="mt-4 rounded-lg border border-neon/25 bg-neon/[0.06] px-3 py-2 text-xs text-neon">Decision pending — enforcement has not run yet.</p>
        ) : (
          <>
        <H>{whyTitle}</H>
        <p className="text-[13px] leading-relaxed">{x.why}</p>

        <H hint={<Badge tone="warn">recommendation · not executed</Badge>}>Recommended response</H>
        <ul className="list-disc space-y-0.5 pl-5 text-xs">{x.recommended.map((r) => <li key={r}>{r}</li>)}</ul>

        <H>Decision summary</H>
        <div className="grid grid-cols-2 gap-2 sm:grid-cols-4">
          <Stat k="risk score"><span className={cn('font-mono text-lg font-semibold', TONE[scoreTone(x.score)].text)}>{x.score}</span></Stat>
          <Stat k="severity"><SeverityBadge severity={x.severity} /></Stat>
          <Stat k="policy decision"><ActionBadge action={x.decision} /></Stat>
          <Stat k="enforcement"><Badge tone={x.enforcement === 'blocked' ? 'danger' : x.enforcement === 'held' ? 'warn' : x.enforcement === 'recommended only' ? 'muted' : 'ok'}>{x.enforcement}</Badge></Stat>
        </div>
        <div className="mt-2 grid gap-2 sm:grid-cols-3">
          <Phase label="Detected" tone="neon" text={x.detected.join(' · ')} />
          <Phase label="Recommended" tone="warn" text={x.recommendedAction} />
          <Phase label="Enforced" tone={actionTone(x.decision) === 'danger' && x.enforcement === 'blocked' ? 'danger' : 'muted'} text={x.enforcedText} />
        </div>
        {x.policies.length > 0 && (
          <div className="mt-2 flex flex-wrap items-center gap-1.5 text-[11px]"><span className="text-muted">Policies:</span>{x.policies.map((p) => <Tip key={p.id} text={p.text}><Badge tone="muted">{p.id}</Badge></Tip>)}</div>
        )}
        {x.related.length > 0 && (
          <div className="mt-1.5 flex flex-wrap items-center gap-1.5 text-[11px]"><span className="text-muted">Related events:</span>
            {x.related.map((id) => <button key={id} onClick={() => openEvent(id)} className="rounded border border-line/10 px-1.5 py-0.5 font-mono text-[10.5px] text-neon hover:border-neon/40">{id}</button>)}</div>
        )}
          </>
        )}
      </motion.div>
    </section>
  );
}

const Stat = ({ k, children }: { k: string; children: ReactNode }) => (
  <div className="rounded-lg border border-line/[0.08] bg-bg/50 px-3 py-2"><div className="label !text-[9.5px]">{k}</div><div className="mt-1">{children}</div></div>
);
const Phase = ({ label, tone, text }: { label: string; tone: 'neon' | 'warn' | 'danger' | 'muted'; text: string }) => (
  <div className={cn('rounded-lg border px-3 py-2', TONE[tone].border, TONE[tone].bg)}>
    <div className={cn('font-mono text-[10px] font-semibold uppercase tracking-[0.16em]', TONE[tone].text)}>{label}</div>
    <p className="mt-0.5 text-[11.5px] leading-snug">{text}</p>
  </div>
);
